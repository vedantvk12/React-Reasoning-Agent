"""
Main CLI entry point for the ReAct Travel Planning Agent.
Coordinates goal analysis, ReAct execution, dynamic replanning, trace logging, and report generation.
"""

import argparse
import json
import os
import sys
from models import TaskStatus
from planner import GoalAnalyzer
from agent import ReActAgent


DEFAULT_GOAL = (
    "Plan a 2-day trip to Goa for 2 people within a budget of ₹10,000, "
    "including transportation, accommodation, food, and sightseeing."
)


